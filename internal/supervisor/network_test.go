package supervisor

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

// TestNameservers checks which servers are taken from a container's
// resolver configuration: the IPv4 ones, in order, with the DNS port,
// and none from comments, other directives, IPv6 servers or a file that
// is not there. The file is rewritten between two readings, as an
// engine rewrites one after attaching a container's network.
func TestNameservers(t *testing.T) {
	path := filepath.Join(t.TempDir(), "resolv.conf")

	if got := nameservers(path); got != nil {
		t.Errorf("a missing file gave %v", got)
	}

	early := "# Generated by Docker Engine.\nnameserver 100.100.100.100\nnameserver fd7a:115c:a1e0::53\nsearch example.net\noptions edns0\n"
	if err := os.WriteFile(path, []byte(early), 0o644); err != nil {
		t.Fatal(err)
	}
	if got, want := nameservers(path), []string{"100.100.100.100:53"}; !reflect.DeepEqual(got, want) {
		t.Errorf("got %v, want %v", got, want)
	}

	late := "nameserver 127.0.0.11\noptions ndots:0\n"
	if err := os.WriteFile(path, []byte(late), 0o644); err != nil {
		t.Fatal(err)
	}
	if got, want := nameservers(path), []string{"127.0.0.11:53"}; !reflect.DeepEqual(got, want) {
		t.Errorf("after the rewrite: got %v, want %v", got, want)
	}
}
